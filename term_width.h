static inline bool tw_in(const TwRange *tab, int n, uint32_t cp) {
    if (cp < tab[0].lo || cp > tab[n-1].hi) return false;
    int lo = 0, hi = n - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if      (cp < tab[mid].lo) hi = mid - 1;
        else if (cp > tab[mid].hi) lo = mid + 1;
        else return true;
    }
    return false;
}

// Number of terminal cells a codepoint occupies: 0, 1 or 2.
static inline int term_char_width(uint32_t cp) {
    if (cp < 0x300) return 1;   // fast path: ASCII + Latin-1 + Latin Extended
    if (tw_in(TW_ZERO, (int)(sizeof(TW_ZERO)/sizeof(TW_ZERO[0])), cp)) return 0;
    if (tw_in(TW_WIDE, (int)(sizeof(TW_WIDE)/sizeof(TW_WIDE[0])), cp)) return 2;
    return 1;
}

// Precomposed form of base+mark, or 0 if there is none.
static inline uint32_t term_compose(uint32_t base, uint32_t mark) {
    int lo = 0, hi = (int)(sizeof(TW_COMP)/sizeof(TW_COMP[0])) - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        const TwComp &c = TW_COMP[mid];
        if (base < c.base || (base == c.base && mark < c.mark)) hi = mid - 1;
        else if (base > c.base || mark > c.mark)                lo = mid + 1;
        else return c.composed;
    }
    return 0;
}
